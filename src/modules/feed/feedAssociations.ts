export const pickFeedMemoryCue = (pool: FeedSymbolPool, char: string, offset = 0) => {
  const source = pool === 'letters' ? LETTER_MEMORY_CUES : NUMBER_MEMORY_CUES;
  const list = source[char] || [];
  if (list.length === 0) return pool === 'letters' ? `${char} 是小鲨鱼的字母点心` : `${char} 是小鲨鱼的数字点心`;
  const index = (Math.floor(Math.random() * list.length) + offset) % list.length;
  return list[index];
};
